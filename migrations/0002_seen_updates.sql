-- Защита от повторной обработки одного и того же сообщения/нажатия (например, если Telegram доставил его дважды
-- или одновременно работают два экземпляра бота). Ключ вставляется атомарно: кто вставил — тот и обрабатывает.
CREATE TABLE seen_update (
    key        TEXT PRIMARY KEY,
    created_at TEXT NOT NULL
);
