// Владелец исправляет начальные показания в Mini App; после первого счёта кнопка пропадает.
import { chromium } from 'playwright-core';
const BASE = process.env.BASE ?? 'http://127.0.0.1:8099';
const browser = await chromium.launch({ executablePath: process.env.CHROME ?? '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] });
const check = (c, m) => { if (!c) { console.error('FAIL:', m); process.exit(1); } console.log('ok:', m); };
const initData = await (await fetch(`${BASE}/dev/init?user=71`)).text();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
await ctx.route('**/telegram-web-app.js', (r) => r.abort());
await ctx.addInitScript((d) => { window.Telegram = { WebApp: { initData: d, colorScheme: 'light', ready() {}, expand() {}, close() {}, onEvent() {}, setHeaderColor() {}, setBackgroundColor() {}, disableVerticalSwipes() {}, BackButton: { show() {}, hide() {}, onClick() {}, offClick() {} }, HapticFeedback: { impactOccurred() {}, notificationOccurred() {} } } }; }, initData);
const page = await ctx.newPage();
page.on('pageerror', (e) => check(false, 'ошибка страницы: ' + e.message));
const token = (await (await fetch(`${BASE}/api/auth/telegram`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ init_data: initData }) })).json()).token;
const H = { 'content-type': 'application/json', authorization: `Bearer ${token}` };
await fetch(`${BASE}/api/register`, { method: 'POST', headers: H, body: '{}' });
const mk = await (await fetch(`${BASE}/api/properties`, { method: 'POST', headers: H, body: JSON.stringify({ name: 'Кв на Ленина', tenant_name: 'Жилец', baselines: { cold: '1', hot: '1', t1: '1', t2: '1' }, prices: { cold: '10', hot: '20', t1: '5', t2: '3' }, sewer_price: '7', proof_required: false }) })).json();
await page.goto(BASE);
await page.getByRole('button', { name: 'Квартира', exact: true }).click();
await page.getByRole('button', { name: 'Исправить начальные показания' }).click();
await page.getByLabel(/Холодная/).first().fill('abc');
await page.getByRole('button', { name: 'Сохранить' }).click();
await page.getByText('Нужно неотрицательное число').first().waitFor();
check(true, 'нечисло отклонено на форме');
await page.getByLabel(/Холодная/).first().fill('123,5');
await page.getByRole('button', { name: 'Сохранить' }).click();
await page.getByText('Начальные показания сохранены').waitFor();
const prop = (await (await fetch(`${BASE}/api/property`, { headers: { ...H, 'x-property-id': String(mk.property.id) } })).json()).property;
check(prop.registers.find((r) => r.code === 'cold').baseline === '123.5', 'сервер хранит 123.5');
await browser.close();
console.log('BASELINES E2E OK');
